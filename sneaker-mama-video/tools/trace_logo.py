"""Vectorize the SNEAKER MAMA logo (figure + wordmark) into SVG path data.

Usage: python3 tools/trace_logo.py <logo.jpg> src/logo-paths.js [wordmark.png]
The optional wordmark PNG (transparent background) gives a sharper wordmark:
its alpha is upsampled 8x before tracing for smooth sub-pixel outlines.
Outputs a JS module with two path strings in a normalized coordinate space
(figure: width 1000 units; wordmark: width 1000 units).
"""
import sys, json
import numpy as np
from PIL import Image
from scipy import ndimage
from skimage import measure

src, out = sys.argv[1], sys.argv[2]
wm_src = sys.argv[3] if len(sys.argv) > 3 else None
img = np.asarray(Image.open(src).convert("RGB")).astype(float) / 255.0
r, g, b = img[..., 0], img[..., 1], img[..., 2]

pink = (r > 0.8) & (g < 0.8) & (b > 0.6) & (r - g > 0.15)
dark = (r + g + b) / 3 < 0.45


def glyphs(mask, tol):
    """Split the wordmark into per-letter paths (connected components)."""
    mask = ndimage.binary_opening(mask, iterations=1)
    lab, n = ndimage.label(mask)
    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    scale = 1000.0 / (x1 - x0)
    out = []
    for i in range(1, n + 1):
        comp = lab == i
        if comp.sum() < 200:
            continue
        cy, cx = np.nonzero(comp)
        soft = ndimage.gaussian_filter(comp.astype(float), 1.0)
        parts = []
        for c in measure.find_contours(soft, 0.5):
            c = measure.approximate_polygon(c, tolerance=tol)
            if len(c) < 4:
                continue
            parts.append("M" + " L".join(f"{(p[1]-x0)*scale:.1f} {(p[0]-y0)*scale:.1f}" for p in c) + "Z")
        out.append({"d": " ".join(parts),
                    "x": round((cx.min() - x0) * scale, 1), "y": round((cy.min() - y0) * scale, 1),
                    "w": round((cx.max() - cx.min()) * scale, 1), "h": round((cy.max() - cy.min()) * scale, 1)})
    # reading order: line (top/bottom), then x
    mid = (y1 - y0) * scale / 2
    out.sort(key=lambda g: (g["y"] + g["h"] / 2 > mid, g["x"]))
    return out


def glyphs_hq(path, up=8, tol=0.9):
    """Per-letter outlines from an anti-aliased PNG wordmark."""
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im)[..., 3].astype(float) / 255.0
    dark = (np.asarray(im.convert("L")) < 128).astype(float)
    cov = a * dark if dark.any() else a
    big = np.asarray(Image.fromarray((cov * 255).astype(np.uint8)).resize((im.width * up, im.height * up), Image.BICUBIC)).astype(float) / 255.0
    big = ndimage.gaussian_filter(big, up * 0.35)
    mask = big > 0.5
    lab, n = ndimage.label(mask)
    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    scale = 1000.0 / (x1 - x0)
    out = []
    for i in range(1, n + 1):
        comp = lab == i
        if comp.sum() < 50 * up * up:
            continue
        cy, cx = np.nonzero(comp)
        field = np.where(ndimage.binary_dilation(comp, iterations=up * 2), big, 0)
        parts = []
        for c in measure.find_contours(field, 0.5):
            c = measure.approximate_polygon(c, tolerance=tol)
            if len(c) < 4:
                continue
            parts.append("M" + " L".join(f"{(p[1]-x0)*scale:.1f} {(p[0]-y0)*scale:.1f}" for p in c) + "Z")
        out.append({"d": " ".join(parts),
                    "x": round((cx.min() - x0) * scale, 1), "y": round((cy.min() - y0) * scale, 1),
                    "w": round((cx.max() - cx.min()) * scale, 1), "h": round((cy.max() - cy.min()) * scale, 1)})
    mid = (y1 - y0) * scale / 2
    out.sort(key=lambda g: (g["y"] + g["h"] / 2 > mid, g["x"]))
    return out


def trace(mask, tol):
    mask = ndimage.binary_opening(mask, iterations=1)
    lab, n = ndimage.label(mask)
    sizes = ndimage.sum(mask, lab, range(1, n + 1))
    keep = np.isin(lab, [i + 1 for i, s in enumerate(sizes) if s > 200])
    soft = ndimage.gaussian_filter(keep.astype(float), 1.2)
    ys, xs = np.nonzero(keep)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    scale = 1000.0 / (x1 - x0)
    parts = []
    for c in measure.find_contours(soft, 0.5):
        c = measure.approximate_polygon(c, tolerance=tol)
        if len(c) < 4:
            continue
        pts = [((p[1] - x0) * scale, (p[0] - y0) * scale) for p in c]
        d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"
        parts.append(d)
    return " ".join(parts), 1000.0, (y1 - y0) * scale


fig_d, fw, fh = trace(pink, 0.6)
wm_d, ww, wh = trace(dark, 0.4)
with open(out, "w") as f:
    f.write("// Auto-generated by tools/trace_logo.py from the brand logo. Do not edit.\n")
    f.write("export const LOGO_FIGURE = " + json.dumps({"d": fig_d, "w": fw, "h": round(fh, 1)}) + ";\n")
    gl = glyphs_hq(wm_src) if wm_src else glyphs(dark, 0.4)
    f.write("export const WORDMARK_GLYPHS = " + json.dumps(gl) + ";\n")
    f.write("export const LOGO_WORDMARK = " + json.dumps({"d": wm_d, "w": ww, "h": round(wh, 1)}) + ";\n")
print("figure", len(fig_d), round(fh), "wordmark", len(wm_d), round(wh))
